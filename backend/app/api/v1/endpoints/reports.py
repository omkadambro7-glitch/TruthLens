router = APIRouter()

@router.get("/share/{token}", response_model=ReportOut)
async def get_shared_report(token: str, db: AsyncSession = Depends(get_db)):
    stmt = (
        select(Report)
        .options(selectinload(Report.job))
        .where(Report.share_token == token)
    )
    result = await db.execute(stmt)
    report = result.scalar_one_or_none()
    
    if not report:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Trust Report not found or link has expired."
        )
        
    if report.is_revoked:
        raise HTTPException(
            status_code=status.HTTP_410_GONE,
            detail="This verification share link was explicitly revoked by the owner."
        )
        
    if report.expires_at and report.expires_at < datetime.now(timezone.utc):
        raise HTTPException(
            status_code=status.HTTP_410_GONE,
            detail="This verification share link has expired."
        )
        
    job = report.job
    return ReportOut(
        report_id=report.id,
        share_token=report.share_token,
        job_id=job.id,
        job_type=job.job_type,
        file_name=job.file_name,
        file_hash_sha256=job.file_hash_sha256,
        manifest_signature=report.manifest_signature,
        verdict_or_risk=job.verdict,
        confidence_or_category=str(job.confidence_score),
        summary=job.summary_text,
        evidence_data=report.report_data,
        is_revoked=report.is_revoked,
        expires_at=report.expires_at,
        created_at=report.created_at,
        disclaimer=(
            "Cryptographically sealed report generated by TruthLens Open Authenticity Consortium. "
            "Documents forensic analysis outputs. Does not constitute official legal finding or medical diagnosis."
        )
    )

