@router.post("/{report_id}/revoke")
async def revoke_report_link(
    report_id: str,
    db: AsyncSession = Depends(get_db)
):
    stmt = select(Report).where((Report.id == report_id) | (Report.job_id == report_id))
    result = await db.execute(stmt)
    report = result.scalar_one_or_none()
    
    if not report:
        raise HTTPException(status_code=404, detail="Report not found.")
        
    report.is_revoked = True
    await db.commit()
    return {"status": "revoked", "message": "Share link has been revoked immediately."}

